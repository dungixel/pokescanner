/** Texto fijo en el idioma actual; {x} se sustituye con las variables dadas */
export function t(key, vars) {
  let s = STR[L][key] ?? STR.es[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, n) => vars[n] ?? '');
  return s;
}
